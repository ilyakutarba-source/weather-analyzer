CREATE TABLE weather_measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temperature_c NUMERIC(5, 2) NOT NULL,
    wind_speed_meters_per_hour NUMERIC(10, 2) NOT NULL,
    pressure_hpa NUMERIC(7, 2) NOT NULL,
    humidity INTEGER NOT NULL,
    weather_condition VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    measured_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_weather_measurements_measured_at
    ON weather_measurements (measured_at);